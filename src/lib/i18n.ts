function fill(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s;
  let out = s;
  for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}

export function lookup(locale: Locale, key: string, vars?: Record<string, string | number>) {
  return fill((locale === "en" ? en : de)[key] ?? de[key] ?? key, vars);
}

export function t(key: string, vars?: Record<string, string | number>) {
  const loc = (useIde.getState().locale as Locale) || "de";
  return lookup(loc, key, vars);
}

export function useT() {
  const locale = useIde((s) => s.locale);
  return useCallback(
    (key: string, vars?: Record<string, string | number>) => lookup(locale || "de", key, vars),
    [locale],
  );
}

export function applyLang(locale: Locale) {
  if (typeof document === "undefined") return;
  document.documentElement.lang = locale;
}
