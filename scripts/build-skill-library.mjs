import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, relative, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const root = resolve(fileURLToPath(new URL('../skills/anvil/', import.meta.url)));
const target = fileURLToPath(new URL('../src/lib/anvil-skills.generated.ts', import.meta.url));
const catalog = JSON.parse(readFileSync(join(root, 'catalog.json'), 'utf8'));
const ids = new Set();
function filesIn(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap(item => {
    if (item.isSymbolicLink()) throw Error('Skill-Ressourcen dürfen keine symbolischen Links enthalten.');
    const path = join(directory, item.name);
    return item.isDirectory() ? filesIn(path) : [path];
  });
}
const skills = catalog.map(meta => {
  if (!/^anvil-[a-z0-9-]+$/.test(meta.id) || ids.has(meta.id)) throw Error(`Ungültige Skill-Kennung: ${meta.id}`);
  ids.add(meta.id);
  const directory = join(root, meta.id);
  const source = readFileSync(join(directory, 'SKILL.md'), 'utf8').replaceAll('\r\n', '\n');
  const match = source.match(/^---\n([\s\S]*?)\n---\n([\s\S]+)$/);
  if (!match) throw Error(`SKILL.md ohne Frontmatter: ${meta.id}`);
  const front = yaml.load(match[1]);
  if (front.name !== meta.id || typeof front.description !== 'string' || !front.description.trim() || !match[2].trim()) throw Error(`Skill-Metadaten fehlen: ${meta.id}`);
  const resources = Object.fromEntries(filesIn(directory).filter(path => path !== join(directory, 'SKILL.md')).map(path => {
    const key = relative(directory, path).replaceAll('\\', '/');
    if (!/^(references|assets)\/[a-zA-Z0-9_./-]+$/.test(key) || !/\.(md|txt|json|svg|html|css|js|py)$/.test(key)) throw Error(`Nicht unterstützte eingebaute Ressource: ${key}`);
    return [key, readFileSync(path, 'utf8')];
  }));
  return { ...meta, description: front.description.trim(), body: match[2].trim(), source, resources };
});
const output = '// Generated by scripts/build-skill-library.mjs from skills/anvil. Edit the skill sources.\nimport type { AnvilSkill } from "./skill-library.ts";\nexport const ANVIL_SKILLS: AnvilSkill[] = ' + JSON.stringify(skills, null, 2) + ';\n';
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw Error('Skill-Bibliothek ist veraltet. npm run build:skills ausführen.');
} else if (!existsSync(target) || readFileSync(target, 'utf8') !== output) writeFileSync(target, output);
console.log(`${skills.length} Anvil-Skills ${process.argv.includes('--check') ? 'geprüft' : 'gebündelt'}.`);
